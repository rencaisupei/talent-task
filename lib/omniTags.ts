/** 全部標籤（已去重） */
export const ALL_TAGS: string[] = Array.from(
  new Set(OMNI_INDUSTRY_TAGS.flatMap((category) => category.tags)),
);

export const TOTAL_TAG_COUNT = ALL_TAGS.length;

export const MAX_TALENT_TAGS = 5;

const tagToCategory = new Map<string, OmniCategory>();
for (const category of OMNI_INDUSTRY_TAGS) {
  for (const tag of category.tags) {
    if (!tagToCategory.has(tag)) tagToCategory.set(tag, category);
  }
}

export function findCategoryByTag(tag: string): OmniCategory | undefined {
  return tagToCategory.get(tag);
}

export function findCategoryById(id: string): OmniCategory | undefined {
  return OMNI_INDUSTRY_TAGS.find((category) => category.id === id);
}
